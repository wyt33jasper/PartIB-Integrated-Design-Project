"""Read the delivery target off a package's QR code.

The Tiny Code Reader decodes the code itself and hands back the text over
I2C. The codes are generated by the department's support/2025_mich_1_qr_codes.py,
which writes exactly:

    "Rack {A|B}, {Upper|Lower}, {1..6}"

so one package carries one of 24 destinations.

Three things shape this module.

Rate limit, not sleep. The reader wants about 50 ms between reads, and the
department's example gets that with sleep(). The main loop cannot block, so
poll() checks the clock instead and returns immediately when a read is not
due yet.

Confirmation. A single misread delivers the package to the wrong depot,
which scores +5 instead of +15. The same text has to decode three times in a
row before poll() reports it. At 50 ms a read that costs about 150 ms, which
is nothing against a five minute run.

Report once. Like the junction detector, poll() returns a target on the pass
that confirms it and then stays quiet, so the caller cannot act on the same
package twice. reset() re-arms it for the next bay.
"""

from utime import ticks_ms, ticks_diff

RACKS = ("A", "B")
LEVELS = ("Upper", "Lower")
MIN_BAY = 1
MAX_BAY = 6


class Target:
    """Where one package has to go: rack A or B, upper or lower, bay 1-6."""

    __slots__ = ("rack", "level", "bay")

    def __init__(self, rack, level, bay):
        self.rack = rack
        self.level = level
        self.bay = bay

    def __eq__(self, other):
        if not isinstance(other, Target):
            return False
        return (self.rack == other.rack and self.level == other.level
                and self.bay == other.bay)

    def __repr__(self):
        return "Rack {}, {}, {}".format(self.rack, self.level, self.bay)


def parse(text):
    """Turn the decoded text into a Target, or None if it is not one.

    Rejects anything that is not exactly the department's format, so a
    smudged or partial decode never reaches the route as a plausible but
    wrong destination. Case and surrounding whitespace are tolerated; the
    reader occasionally returns a trailing newline.
    """
    if not text:
        return None

    parts = text.strip().split(",")
    if len(parts) != 3:
        return None

    rack_field = parts[0].strip()
    level_field = parts[1].strip()
    bay_field = parts[2].strip()

    # "Rack A" - the keyword guards against a code from somewhere else that
    # happens to have two commas in it.
    rack_words = rack_field.split()
    if len(rack_words) != 2 or rack_words[0].lower() != "rack":
        return None
    rack = rack_words[1].upper()
    if rack not in RACKS:
        return None

    level = level_field.capitalize()
    if level not in LEVELS:
        return None

    try:
        bay = int(bay_field)
    except ValueError:
        return None
    if bay < MIN_BAY or bay > MAX_BAY:
        return None

    return Target(rack, level, bay)


class QRReader:
    def __init__(self, code_reader, poll_ms=50, confirm_reads=3):
        """code_reader is anything with a poll() returning text or None,
        normally libs.tiny_code_reader.TinyCodeReader."""
        self._reader = code_reader
        self._poll_ms = poll_ms
        self._confirm_reads = confirm_reads

        self._last_due_ms = ticks_ms()
        self._candidate = None
        self._count = 0
        self._reported = False

        # Consecutive I2C failures. A disconnected reader looks exactly like
        # an empty field of view, so the count is exposed rather than hidden:
        # a bench test can tell "no code here" from "no sensor here".
        self.error_count = 0

    def reset(self):
        """Forget the current read and re-arm for the next package."""
        self._candidate = None
        self._count = 0
        self._reported = False
        self._last_due_ms = ticks_ms()

    @property
    def reading(self):
        """The Target being confirmed, or None. For bench tests and logging."""
        return self._candidate

    @property
    def confirmations(self):
        return self._count

    def poll(self):
        """Return a Target once it has been read confirm_reads times running.

        Returns None on every other pass. Never blocks and never raises: a
        reader that is unplugged or returns rubbish simply yields no target.
        """
        now = ticks_ms()
        if ticks_diff(now, self._last_due_ms) < self._poll_ms:
            return None
        self._last_due_ms = now

        try:
            text = self._reader.poll()
            self.error_count = 0
        except Exception:
            # An I2C read can fail if the reader is unplugged or the bus
            # glitches. Treat it as "nothing seen" so the AGV keeps running.
            self.error_count += 1
            text = None

        target = parse(text)

        if target is None:
            # No code, or one that is not a delivery target. Drop the partial
            # confirmation so an interrupted read cannot be completed later
            # by a different package.
            self._candidate = None
            self._count = 0
            self._reported = False
            return None

        if target != self._candidate:
            # A different code: start confirming this one instead.
            self._candidate = target
            self._count = 1
            self._reported = False
            return None

        self._count += 1
        if self._count < self._confirm_reads or self._reported:
            return None

        self._reported = True
        return target
